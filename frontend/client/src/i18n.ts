export function translate(language: string, value: string): string {
  return language === 'en' ? english[value] || value : value;
}

export function useI18n() {
  const session = useSession();
  const language = computed<'fr' | 'en'>(() => session.user?.language === 'en' ? 'en' : 'fr');
  const t = (value: string) => translate(language.value, value);
  const locale = computed(() => language.value === 'en' ? 'en-US' : 'fr-FR');
  return { language, locale, t };
}
